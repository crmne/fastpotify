def main() -> None:
    LOCALES.mkdir(exist_ok=True)
    missing = set(EN) - set(ES)
    extra = set(ES) - set(EN)
    if missing:
        raise SystemExit(f"es-ES missing keys: {sorted(missing)}")
    if extra:
        raise SystemExit(f"es-ES extra keys: {sorted(extra)}")
    for name, table in [("en.json", EN), ("es-ES.json", ES)]:
        path = LOCALES / name
        path.write_text(
            json.dumps({"strings": table}, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"wrote {path} ({len(table)} keys)")


if __name__ == "__main__":
    main()
